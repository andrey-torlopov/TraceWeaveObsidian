// AJV runs at build time only. The shipped plugin imports ordinary validator functions.
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { _ } from 'ajv/dist/compile/codegen/index.js';

const readSchema = async name => JSON.parse(await readFile(new URL(`../contracts/${name}.schema.json`, import.meta.url), 'utf8'));
const formats = {
  uuid: /^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/u,
  'date-time': { type: 'string', validate: value => !Number.isNaN(Date.parse(value)) },
  uri: { type: 'string', validate: value => { try { new URL(value); return true; } catch { return false; } } },
};
const formatCode = _`({uuid:/^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/u, "date-time":{type:"string",validate:value=>!Number.isNaN(Date.parse(value))}, uri:{type:"string",validate:value=>{try{new URL(value);return true;}catch{return false;}}}})`;
function compiler(strict, archive = false) {
  const ajv = new Ajv2020({ strict, allErrors: false, code: { source: true, esm: true, formats: formatCode }, validateFormats: true });
  if (archive) {
    for (const [name, definition] of Object.entries(formats)) ajv.addFormat(name, definition);
    ajv.addKeyword({ keyword: 'x-maxUtf8Bytes', type: 'string', schemaType: 'number', code(cxt) { cxt.fail(_`Buffer.byteLength(${cxt.data}) > ${cxt.schemaCode}`); } });
    ajv.addKeyword({ keyword: 'x-maxJsonUtf8Bytes', schemaType: 'number', code(cxt) { cxt.fail(_`Buffer.byteLength(JSON.stringify(${cxt.data})) > ${cxt.schemaCode}`); } });
    ajv.addKeyword({ keyword: 'x-normalize', type: 'string', schemaType: 'string', code(cxt) { cxt.fail(_`${cxt.data} !== ${cxt.data}.normalize("NFC").trim()`); } });
    ajv.addKeyword({ keyword: 'x-realCalendarDate', type: 'object', schemaType: 'boolean', code(cxt) {
      cxt.fail(_`!((value)=>{if(typeof value.value!=="string")return false;const date=value.value+(value.precision==="year"?"-01-01":value.precision==="month"?"-01":"");return /^[0-9]{4}-[0-9][0-9]-[0-9][0-9]$/u.test(date)&&!Number.isNaN(Date.parse(date+"T00:00:00.000Z"))&&new Date(date+"T00:00:00.000Z").toISOString().slice(0,10)===date;})(${cxt.data})`);
    } });
  }
  return ajv;
}
const exports = [], sections = [];
function emit(ajv, definitions) {
  sections.push(standaloneCode(ajv, definitions));
  exports.push(...Object.keys(definitions));
}
const local = compiler(true);
const project = await readSchema('obsidian-project'), history = await readSchema('history'), journal = await readSchema('journal');
for (const schema of [project, history, journal]) local.addSchema(schema);
emit(local, { obsidianProject: project.$id, history: history.$id, journal: journal.$id });
const archive = compiler(false, true), schema = await readSchema('archive2.0');
archive.addSchema(schema);
emit(archive, Object.fromEntries(['Manifest', 'Project', 'ReportSnapshot', 'Presentation', 'Origin'].map(name => [`archive${name === 'ReportSnapshot' ? 'Snapshot' : name}`, `${schema.$id}#/$defs/${name}`])));
for (const [profile, filename] of [['Initial', 'legacy-1.0-initial'], ['Modern', 'legacy-1.0-019']]) {
  const ajv = compiler(false), legacy = await readSchema(filename);
  for (const [name, definition] of Object.entries(formats)) ajv.addFormat(name, definition);
  ajv.addSchema(legacy);
  emit(ajv, Object.fromEntries(['Manifest', 'Project'].map(name => [`legacy${profile}${name}`, `${legacy.$id}#/$defs/${name}`])));
}
// Each compiler has its own numbered function scope, so isolate each emitted module.
const imports = new Map();
const modules = sections.map((source, section) => {
  source = source.replace(/require\("(ajv\/dist\/runtime\/[^"\n]+)"\)/gu, (_, name) => {
    if (!imports.has(name)) imports.set(name, `runtime${imports.size}`);
    return imports.get(name);
  });
  const names = [...source.matchAll(/export const (\w+) =/gu)].map(match => match[1]);
  source = source.replaceAll('export const ', 'const ');
  return `const section${section}=(()=>{${source}\nreturn {${names.join(',')}};})();\nexport const {${names.join(',')}}=section${section};\n`;
});
const output = '// Generated by scripts/generate-validators.mjs; do not edit.\n' + [...imports].map(([name, variable]) => `import ${variable} from '${name}.js';`).join('\n') + '\n' + modules.join('\n');
if (/\bnew Function\s*\(|\beval\s*\(/u.test(output)) throw new Error('Runtime code generation leaked into standalone validators');
const folder = new URL('../src/generated/', import.meta.url);
await mkdir(folder, { recursive: true });
await writeFile(new URL('validators.js', folder), output);
await writeFile(new URL('validators.d.ts', folder), '// Generated by scripts/generate-validators.mjs; do not edit.\nimport type { ValidateFunction } from "ajv";\n' + exports.map(name => `export const ${name}: ValidateFunction;`).join('\n') + '\n');
console.log(`Generated ${exports.length} standalone schema validators without runtime compilation.`);
