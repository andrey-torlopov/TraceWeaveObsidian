import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

const sourceURL = new URL('../contracts/unicode/CaseFolding-17.0.0.txt', import.meta.url);
const outputURL = new URL('../src/casefold.ts', import.meta.url);
const source = await readFile(sourceURL);
const sha256 = createHash('sha256').update(source).digest('hex');
if (sha256 !== 'ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183') throw new Error('Unicode17 casefold source differs from its pinned digest');
const mappings = new Map();
for (const line of source.toString('utf8').split(/\r?\n/u)) {
  const data = line.split('#')[0].trim(); if (!data) continue;
  const [code, status, mapping] = data.split(';').map(value => value.trim());
  if (status !== 'C' && status !== 'F') continue;
  const point = Number.parseInt(code, 16); if (mappings.has(point)) throw new Error('Duplicate full casefold code point');
  mappings.set(point, String.fromCodePoint(...mapping.split(' ').map(value => Number.parseInt(value, 16))));
}
const entries = [...mappings].sort(([left], [right]) => left - right).map(([point, value]) => `  [0x${point.toString(16).toUpperCase()}, ${JSON.stringify(value)}],`).join('\n');
const result = `// Generated by scripts/generate-casefold.mjs from Unicode17 CaseFolding C/F mappings.\n// Source: https://www.unicode.org/Public/17.0.0/ucd/CaseFolding.txt\n// License: UNICODE-LICENSE. Unlisted code points map to themselves; S/T are excluded.\nexport const caseFoldVersion = '17.0.0';\nexport const caseFoldSourceSHA256 = '${sha256}';\nconst fullMappings = new Map<number, string>([\n${entries}\n]);\n\n/** Full default Unicode17 case folding with canonical normalization. */\nexport function caseFold(value: string): string {\n  let output = '';\n  for (const character of value.normalize('NFC')) output += fullMappings.get(character.codePointAt(0)!) ?? character;\n  return output.normalize('NFC');\n}\n`;
await writeFile(outputURL, result, 'utf8');
process.stdout.write(`Generated Unicode17 full casefold table: ${mappings.size} mappings; SHA-256 ${sha256}\n`);
